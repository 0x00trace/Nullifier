//! Which title memory the title wrote since a host copy took it (decision
//! 0007, "Copies of title memory"). The runtime reserves title GPU memory
//! with write watching (`victory-hle` xmem), so the kernel keeps a dirty bit
//! per 4 KiB page; asking for a range's written pages also clears them. Host
//! copies of the same memory can overlap (nested buffers, textures in
//! buffers), so what one asks is kept here for the others: a journal of
//! each page's last write, numbered by the asking.
//!
//! Physical-page views (xmem's sections) cannot be write-watched. There a
//! copy leaves each 64 KiB block it took read-only, and our vectored handler
//! takes the first write to it: it notes the block as written and gives the
//! write access back. The runtime tells us when it maps or unmaps views
//! ([`title_memory_remapped`]), which resets their protection. Blocks found
//! wholly uncommitted are skipped while they remain so; one query can
//! confirm a whole region, including ordinary reservations between views.
//!
//! Writes into physical pages through another view are seen too: the
//! runtime tells us the views of the pages it wrote itself ([`writing`],
//! xmem's `write_physical` and DirectStorage's page destinations), and a
//! write by the title through any view of a guarded page faults like one
//! at the guarded address (the guard makes every view of the page
//! read-only, [`open`] gives them all back; not a page of more than
//! [`MANY_VIEWS`] views). A
//! system call writing into a guarded block fails (none is known to).

use std::collections::BTreeMap;
use std::sync::Mutex;

/// The unit tracked and copied: 64 KiB, the console's page (the kernel's
/// 4 KiB pages fold into it). Finer units made the checks of the world's
/// big buffers cost more than the copies they saved.
pub(crate) const PAGE: usize = 64 << 10;
/// The kernel's page, the unit of its answers.
const KERNEL_PAGE: usize = 4096;

struct Journal {
    /// Numbers the askings; 0 is "never".
    asked: u64,
    /// Page number → the asking that last found it written.
    written: BTreeMap<usize, u64>,
    /// Room for the kernel's answer.
    found: Vec<usize>,
    /// Page ranges asked ahead for a submission's refreshes ([`ask_ahead`])
    /// and the asking that did: `writes` answers for a range inside one
    /// from the journal, without another kernel call.
    ahead: Vec<(usize, usize)>,
    ahead_asked: u64,
    /// The ahead asking stands for a whole submission ([`ask_once`]): no
    /// other ahead asking is made, and `ahead` stays, until
    /// [`ask_once_end`].
    kept: bool,
    /// Page ranges the kernel refused an asking for ([`ask_kernel`]): not
    /// write-watched memory of one reservation. They are not asked about
    /// again until [`REFUSED_FOR`] askings have gone by.
    refused: Option<std::collections::HashSet<(usize, usize)>>,
    /// The asking at which `refused` was last emptied.
    refused_at: u64,
}

static JOURNAL: Mutex<Journal> = Mutex::new(Journal {
    asked: 0,
    written: BTreeMap::new(),
    found: Vec::new(),
    ahead: Vec::new(),
    ahead_asked: 0,
    kept: false,
    refused: None,
    refused_at: 0,
});

/// How many askings a range the kernel refused is left unasked for
/// ([`Journal::refused`]): a submission's ranges are asked about together,
/// by halves where the kernel refuses a run, and a view among them (never
/// write-watched) was refused again at every level, in every submission:
/// about 4,400 of a frame's 7,300 askings in the world. Memory that turns
/// from a view into write-watched memory without a mapping told to us is
/// asked about again after this many askings at the latest; until then its
/// writes are found by [`writes`], which asks the kernel itself.
const REFUSED_FOR: u64 = 4096;

/// Ranges of one submission closer than this are asked about together:
/// walking the pages between them costs less than another kernel call (a
/// call that resets written pages costs 30-70 microseconds whatever the
/// range).
const AHEAD_GAP: usize = (8 << 20) / PAGE;
/// The most one asking covers (its answer needs 8 bytes per 4 KiB page).
const AHEAD_MAX: usize = (1 << 30) / PAGE;

/// Asks the kernel about many ranges `(start, end)` at once, before the
/// [`writes`] of each: ranges close together are one asking, and `writes`
/// then answers from the journal until [`ask_ahead_done`]. The world's
/// submissions refresh thousands of host copies (6,664 askings a frame,
/// 456 ms, in run 14). Ranges that are not write-watched, or lie alone, are
/// left to `writes`.
pub(crate) fn ask_ahead(ranges: &[(usize, usize)]) {
    let mut pieces: Vec<(usize, usize)> = ranges
        .iter()
        .filter(|r| r.0 < r.1)
        .map(|&(start, end)| (start / PAGE, end.div_ceil(PAGE)))
        .collect();
    if pieces.len() < 2 {
        return;
    }
    pieces.sort_unstable();
    let mut j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    let j = &mut *j;
    // The submission's one asking stands ([`ask_once`]): what it does not
    // hold is left to `writes`.
    if j.kept {
        return;
    }
    j.asked += 1;
    j.ahead_asked = j.asked;
    j.ahead.clear();
    let mut i = 0;
    while i < pieces.len() {
        let first = pieces[i].0;
        let mut last = pieces[i].1;
        let mut k = i + 1;
        while k < pieces.len()
            && pieces[k].0 <= last + AHEAD_GAP
            && last.max(pieces[k].1) - first <= AHEAD_MAX
        {
            last = last.max(pieces[k].1);
            k += 1;
        }
        ask_run(j, &pieces[i..k]);
        i = k;
    }
}

/// Since the last frame line: the kernel askings that took a millisecond
/// or more, their microseconds, and the longest asking's. An asking walks
/// page tables, some ten microseconds for most ranges; in run 75 the 2,644
/// askings of a frame took 219 ms in the lines where the pass over the
/// heap's views ran long, 25-50 ms in the others. These numbers say
/// whether a few askings wait for something or all of them are slow.
#[cfg(feature = "diagnostics")]
static SLOW: [std::sync::atomic::AtomicU64; 3] = [const { std::sync::atomic::AtomicU64::new(0) }; 3];

#[cfg(feature = "diagnostics")]
fn slow(us: u64) {
    use std::sync::atomic::Ordering::Relaxed;
    if us >= 1000 {
        SLOW[0].fetch_add(1, Relaxed);
        SLOW[1].fetch_add(us, Relaxed);
    }
    SLOW[2].fetch_max(us, Relaxed);
}

/// [`SLOW`], taken.
#[cfg(feature = "diagnostics")]
pub(crate) fn slow_asks() -> [u64; 3] {
    [0, 1, 2].map(|i| SLOW[i].swap(0, std::sync::atomic::Ordering::Relaxed))
}

/// The submission's refreshes are done: `writes` asks the kernel again.
pub(crate) fn ask_ahead_done() {
    let mut j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    if !j.kept {
        j.ahead.clear();
    }
}

/// Whether a submission asks the kernel once, before its first refresh,
/// about every range its lists refresh (`VICTORY_ASK_ONCE=1`; off by
/// default).
///
/// A submission's refreshes are done in groups, between the title's own
/// buffer copies (each copy flushes the refreshes recorded before it), and
/// every group asked the kernel again: 2,644 askings a frame, 70 a
/// submission. With the switch the journal answers all of them from one
/// asking made when the submission starts.
///
/// What changes: memory the title's other threads write while the
/// submission is being prepared is seen by the next submission's asking,
/// not by this one's later groups. What this submission's lists read was
/// written before they were submitted, so before the asking. Our own
/// writes into title memory while preparing are told to the journal
/// ([`wrote`]) or end the asking ([`ask_once_end`]).
pub(crate) fn once() -> bool {
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    // On by default since run 81 (with card buffers: 375-450 ms a frame
    // against 573-647, the picture unchanged over four minutes);
    // `VICTORY_ASK_ONCE=0` asks per range, as before.
    *ON.get_or_init(|| std::env::var_os("VICTORY_ASK_ONCE").is_none_or(|v| v != "0"))
}

/// With [`once`]: asks about `ranges` (everything a submission's lists
/// refresh) as [`ask_ahead`] does, and lets that asking stand until
/// [`ask_once_end`].
pub(crate) fn ask_once(ranges: &[(usize, usize)]) {
    if !once() {
        return;
    }
    ask_once_end();
    ask_ahead(ranges);
    let mut j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    let j = &mut *j;
    if j.ahead.is_empty() {
        // `ask_ahead` asked nothing (fewer than two ranges).
        j.asked += 1;
        j.ahead_asked = j.asked;
    }
    // `ask_ahead` leaves a range that lies alone to `writes`, which asks
    // once per flush: with one asking for the submission that was every
    // such range asked again at each of its 70 flushes (run 76: 2,300
    // askings a frame with the switch on, as without it). They are asked
    // here, once; what is not write-watched stays with `writes`.
    for &(start, end) in ranges {
        if start >= end {
            continue;
        }
        let (first, last) = (start / PAGE, end.div_ceil(PAGE));
        if !j.ahead.iter().any(|&(a, b)| a <= first && last <= b) && ask_kernel(j, first, last) {
            j.ahead.push((first, last));
        }
    }
    j.kept = !j.ahead.is_empty();
}

/// The submission's one asking stands no longer: its refreshes are done,
/// or title memory was written in a way the journal was not told.
pub(crate) fn ask_once_end() {
    let mut j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    if j.kept {
        j.kept = false;
        j.ahead.clear();
    }
}

/// We wrote title memory `[at, at + len)` while a submission's one asking
/// stands (the title's buffer copies, done at submission): its pages count
/// as written after that asking, so the refreshes that follow copy them.
pub(crate) fn wrote(at: usize, len: usize) {
    let mut j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    if !j.kept || len == 0 {
        return;
    }
    j.asked += 1;
    let now = j.asked;
    for page in at / PAGE..at.saturating_add(len).div_ceil(PAGE) {
        j.written.insert(page, now);
    }
}

/// We wrote the 64 KiB page numbered `page` of title memory through a
/// view of our own (`crate::inplace::write_own`): no guard was opened and
/// no kernel write-watch bit set, so the journal is told here. The page,
/// and the same physical page at its other title addresses (`others`,
/// page numbers), count as written at a new asking, which every host copy
/// that holds them takes at its next refresh. Returns the asking that had
/// last found `page` written (0: never) and the new one, for the copy
/// that wrote to note itself current.
pub(crate) fn wrote_own(page: usize, others: &[usize]) -> (u64, u64) {
    let mut j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    let j = &mut *j;
    j.asked += 1;
    let now = j.asked;
    // An asking that stands for a submission moves with it: a copy taking
    // the page at the standing asking would find it written "later" at
    // every refresh until that asking ends.
    if j.kept || !j.ahead.is_empty() {
        j.ahead_asked = now;
    }
    let before = j.written.insert(page, now).unwrap_or(0);
    for &other in others {
        if other != page {
            j.written.insert(other, now);
        }
    }
    (before, now)
}

/// One kernel asking for `pieces` (page ranges in order); by halves if it
/// fails, as a run across two reservations or into memory that is not
/// write-watched does. A piece alone is left to [`writes`].
fn ask_run(j: &mut Journal, pieces: &[(usize, usize)]) {
    if pieces.len() < 2 {
        return;
    }
    let first = pieces[0].0;
    let last = pieces.iter().map(|p| p.1).max().unwrap_or(first);
    if ask_kernel(j, first, last) {
        j.ahead.push((first, last));
        return;
    }
    let (a, b) = pieces.split_at(pieces.len() / 2);
    ask_run(j, a);
    ask_run(j, b);
}

/// Asks the kernel for the written pages of pages `[first, last)` and notes
/// them in the journal under the ahead asking; false (and nothing changed)
/// if the range is not write-watched memory of one reservation.
fn ask_kernel(j: &mut Journal, first: usize, last: usize) -> bool {
    use windows_sys::Win32::System::Memory::GetWriteWatch;
    const WRITE_WATCH_FLAG_RESET: u32 = 1;
    if j.asked.saturating_sub(j.refused_at) >= REFUSED_FOR {
        j.refused_at = j.asked;
        j.refused = None;
    }
    if j.refused
        .as_ref()
        .is_some_and(|r| r.contains(&(first, last)))
    {
        return false;
    }
    let mut count = (last - first) * PAGE / KERNEL_PAGE;
    j.found.resize(count.max(j.found.len()), 0);
    let mut granularity = 0;
    #[cfg(feature = "diagnostics")]
    let started = crate::clock::Stamp::now();
    // SAFETY: the answer buffer holds `count` entries.
    let mut failed = unsafe {
        GetWriteWatch(
            WRITE_WATCH_FLAG_RESET,
            (first * PAGE) as *const _,
            (last - first) * PAGE,
            j.found.as_mut_ptr().cast(),
            &mut count,
            &mut granularity,
        )
    } != 0;
    // Diagnostic (docs/ROADMAP.md P0): if Wine's GetWriteWatch reports the
    // whole range as written or never resets, every texture looks dirty every
    // frame. VICTORY_NO_WRITEWATCH=1 forces the guard path to measure that.
    static NO_WW: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    if *NO_WW.get_or_init(|| std::env::var_os("VICTORY_NO_WRITEWATCH").is_some()) {
        failed = true;
    }
    if failed {
        j.refused
            .get_or_insert_with(Default::default)
            .insert((first, last));
        return false;
    }
    #[cfg(feature = "diagnostics")]
    {
        use crate::copystat::{C, add};
        add(C::Watches, 1);
        add(C::WatchUs, started.elapsed().as_micros() as u64);
        slow(started.elapsed().as_micros() as u64);
    }
    let now = j.ahead_asked;
    for k in 0..count {
        let page = j.found[k] / PAGE;
        j.written.insert(page, now);
    }
    true
}

/// What [`writes`] would say of `[start, end)` from the journal alone, if
/// the range lies in one asked ahead ([`ask_ahead`], [`ask_once`]): the
/// pages written since tracking began and the asking that last found each
/// written, with the number of the asking that stands (as [`writes`] gives
/// it). `None` if the kernel would have to be asked.
pub(crate) fn asked(start: usize, end: usize) -> Option<(u64, Vec<(usize, u64)>)> {
    let (first, last) = (start / PAGE, end.div_ceil(PAGE));
    let j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    j.ahead
        .iter()
        .any(|&(a, b)| a <= first && last <= b)
        .then(|| (j.ahead_asked, j.written.range(first..last).map(|(&p, &w)| (p, w)).collect()))
}

/// The pages of `[start, end)` (whole pages) as last written, for pages
/// written since tracking began: `(page number, asking)` in page order, and
/// this asking's number, which is higher than any in the list but those the
/// kernel just reported. `None` if the memory is not write-watched (nor,
/// with `guarded`, view memory, which is then guarded).
pub(crate) fn writes(start: usize, end: usize, guarded: bool) -> Option<(u64, Vec<(usize, u64)>)> {
    use windows_sys::Win32::System::Memory::GetWriteWatch;
    const WRITE_WATCH_FLAG_RESET: u32 = 1;
    let (first, last) = (start / PAGE, end.div_ceil(PAGE));
    let mut j = JOURNAL.lock().unwrap_or_else(|e| e.into_inner());
    let j = &mut *j;
    // Asked ahead with the submission's other ranges: the journal has it.
    if j.ahead.iter().any(|&(a, b)| a <= first && last <= b) {
        return Some((
            j.ahead_asked,
            j.written
                .range(first..last)
                .map(|(&p, &w)| (p, w))
                .collect(),
        ));
    }
    let mut count = (last - first) * PAGE / KERNEL_PAGE;
    let mut granularity = 0;
    #[cfg(feature = "diagnostics")]
    let started = crate::clock::Stamp::now();
    // A range the guards hold the first block of is a view (`guard` goes
    // by the same): the kernel keeps no write watch for it and refuses,
    // so it is not asked.
    let mut failed = guarded && known_view(first);
    if !failed {
        j.found.resize(count.max(j.found.len()), 0);
        // SAFETY: the answer buffer holds `count` entries.
        failed = unsafe {
            GetWriteWatch(
                WRITE_WATCH_FLAG_RESET,
                (first * PAGE) as *const _,
                (last - first) * PAGE,
                j.found.as_mut_ptr().cast(),
                &mut count,
                &mut granularity,
            )
        } != 0;
    }
    // Diagnostic (docs/ROADMAP.md P0): if Wine's GetWriteWatch reports the
    // whole range as written or never resets, every texture looks dirty every
    // frame. VICTORY_NO_WRITEWATCH=1 forces the guard path to measure that.
    static NO_WW: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    if *NO_WW.get_or_init(|| std::env::var_os("VICTORY_NO_WRITEWATCH").is_some()) {
        failed = true;
    }
    let guarded = if failed {
        count = 0;
        if !guarded {
            return None;
        }
        #[cfg(feature = "diagnostics")]
        let guarding = crate::clock::Stamp::now();
        let written = guard(first * PAGE, last * PAGE);
        #[cfg(feature = "diagnostics")]
        crate::copystat::add(crate::copystat::C::GuardUs, guarding.elapsed().as_micros() as u64);
        written?
    } else {
        Vec::new()
    };
    #[cfg(feature = "diagnostics")]
    {
        use crate::copystat::{C, add};
        add(C::Watches, 1);
        add(C::WatchUs, started.elapsed().as_micros() as u64);
        slow(started.elapsed().as_micros() as u64);
    }
    j.asked += 1;
    let now = j.asked;
    let pages = j.found[..count].iter().map(|&at| at / PAGE).chain(guarded);
    for page in pages.collect::<Vec<_>>() {
        j.written.insert(page, now);
    }
    Some((
        now,
        j.written
            .range(first..last)
            .map(|(&p, &w)| (p, w))
            .collect(),
    ))
}

/// Guarded blocks of view memory.
const BLOCK: usize = PAGE;

/// A set of block numbers kept as bits, 65,536 blocks (4 GiB of addresses)
/// to a chunk, the chunks in address order.
///
/// The guards' sets were ordered sets of numbers. A frame asks about some
/// 13 GB of view memory, 200,000 blocks, nearly all of them clean, and
/// reading the clean blocks of each asked range off such a set, then
/// looking single blocks up in it, was 6 ms a frame of the thread that
/// submits (docs/FINDINGS.md 2.10: the lookups, and `guard` itself). As
/// bits a range that is all clean is a few words counted.
struct Blocks {
    chunks: BTreeMap<usize, Box<[u64; Blocks::WORDS]>>,
    len: usize,
}

impl Blocks {
    /// Blocks to a chunk, as a shift.
    const SHIFT: usize = 16;
    const WORDS: usize = 1 << (Self::SHIFT - 6);

    const fn new() -> Self {
        Self {
            chunks: BTreeMap::new(),
            len: 0,
        }
    }

    fn is_empty(&self) -> bool {
        self.len == 0
    }

    fn contains(&self, block: &usize) -> bool {
        self.chunks
            .get(&(block >> Self::SHIFT))
            .is_some_and(|words| words[(block >> 6) & (Self::WORDS - 1)] >> (block & 63) & 1 != 0)
    }

    /// Whether the block was not in the set before.
    fn insert(&mut self, block: usize) -> bool {
        let words = self
            .chunks
            .entry(block >> Self::SHIFT)
            .or_insert_with(|| Box::new([0; Self::WORDS]));
        let (word, bit) = (
            &mut words[(block >> 6) & (Self::WORDS - 1)],
            1u64 << (block & 63),
        );
        let new = *word & bit == 0;
        *word |= bit;
        self.len += usize::from(new);
        new
    }

    /// Whether the block was in the set.
    fn remove(&mut self, block: &usize) -> bool {
        let Some(words) = self.chunks.get_mut(&(block >> Self::SHIFT)) else {
            return false;
        };
        let (word, bit) = (
            &mut words[(block >> 6) & (Self::WORDS - 1)],
            1u64 << (block & 63),
        );
        let was = *word & bit != 0;
        *word &= !bit;
        self.len -= usize::from(was);
        was
    }

    /// Adds every block of `blocks` (a range of memory that is there: every
    /// chunk it touches is made).
    fn extend(&mut self, blocks: std::ops::Range<usize>) {
        let (mut at, to) = (blocks.start, blocks.end);
        while at < to {
            let chunk = at >> Self::SHIFT;
            let base = chunk << Self::SHIFT;
            let end = to.min(base + (1 << Self::SHIFT));
            let words = self
                .chunks
                .entry(chunk)
                .or_insert_with(|| Box::new([0; Self::WORDS]));
            while at < end {
                let w = (at - base) >> 6;
                let first = base + (w << 6);
                let mut mask = !0u64 << (at - first);
                if first + 64 > end {
                    mask &= !0u64 >> (first + 64 - end);
                }
                self.len += (mask & !words[w]).count_ones() as usize;
                words[w] |= mask;
                at = (first + 64).min(end);
            }
        }
    }

    /// Calls `each` for every word that holds blocks of `blocks`, in order:
    /// the number of the word's first block, the word, and the bits of it
    /// that lie in the range. Only the chunks there are are looked at, so
    /// the range may be as long as the address space.
    fn words(&self, blocks: std::ops::Range<usize>, mut each: impl FnMut(usize, u64, u64)) {
        let (from, to) = (blocks.start, blocks.end);
        if from >= to {
            return;
        }
        for (&chunk, words) in self
            .chunks
            .range(from >> Self::SHIFT..=(to - 1) >> Self::SHIFT)
        {
            let base = chunk << Self::SHIFT;
            let (lo, hi) = (from.max(base), to.min(base + (1 << Self::SHIFT)));
            for w in (lo - base) >> 6..=(hi - 1 - base) >> 6 {
                let first = base + (w << 6);
                let mut mask = !0u64;
                if first < lo {
                    mask &= !0u64 << (lo - first);
                }
                if first + 64 > hi {
                    mask &= !0u64 >> (first + 64 - hi);
                }
                each(first, words[w], mask);
            }
        }
    }

    /// How many blocks of `blocks` are in the set.
    fn count(&self, blocks: std::ops::Range<usize>) -> usize {
        let mut n = 0;
        self.words(blocks, |_, word, mask| {
            n += (word & mask).count_ones() as usize
        });
        n
    }

    /// The blocks of `blocks` that are in the set, in order.
    fn within(&self, blocks: std::ops::Range<usize>) -> Vec<usize> {
        let mut found = Vec::new();
        self.words(blocks, |first, word, mask| {
            let mut bits = word & mask;
            while bits != 0 {
                found.push(first + bits.trailing_zeros() as usize);
                bits &= bits - 1;
            }
        });
        found
    }

    /// The first block of `[from, to)` that is not in the set; `to` if
    /// they all are.
    fn first_out(&self, from: usize, to: usize) -> usize {
        let mut at = from;
        while at < to {
            let chunk = at >> Self::SHIFT;
            let Some(words) = self.chunks.get(&chunk) else {
                return at;
            };
            let base = chunk << Self::SHIFT;
            let end = to.min(base + (1 << Self::SHIFT));
            while at < end {
                let w = (at - base) >> 6;
                let first = base + (w << 6);
                let out = !words[w] & (!0u64 << (at - first));
                if out != 0 {
                    return (first + out.trailing_zeros() as usize).min(to);
                }
                at = first + 64;
            }
        }
        to
    }
}

struct Guards {
    /// Blocks we made read-only.
    protected: Blocks,
    /// Of those, the ones not written since a copy took them.
    clean: Blocks,
    /// Blocks already copied as zeros. While they remain wholly uncommitted,
    /// the copy can skip hundreds of MB of failing kernel reads per world frame.
    absent: Blocks,
    /// Blocks whose physical page was guarded together with its other views
    /// (those views' blocks are in it too): a write to one opens them all.
    /// A write range can be huge (`fread`), so only these are looked up.
    aliased: Blocks,
}

static GUARDS: Mutex<Guards> = Mutex::new(Guards {
    protected: Blocks::new(),
    clean: Blocks::new(),
    absent: Blocks::new(),
    aliased: Blocks::new(),
});

fn guards() -> std::sync::MutexGuard<'static, Guards> {
    GUARDS.lock().unwrap_or_else(|e| e.into_inner())
}

/// Whether the 64 KiB page numbered `page` is guarded and not written
/// since a copy took it (for `VICTORY_BACK_OWN_CHECK=1`).
pub(crate) fn clean(page: usize) -> bool {
    guards().clean.contains(&page)
}

/// Whether `block` is view memory by what the guards hold (read-only by
/// our hand, or noted absent), without a question to Windows; never with
/// `VICTORY_GUARD_ASK=1`.
fn known_view(block: usize) -> bool {
    static ASK: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    !*ASK.get_or_init(|| std::env::var_os("VICTORY_GUARD_ASK").is_some_and(|v| v == "1")) && {
        let g = guards();
        g.protected.contains(&block) || g.absent.contains(&block)
    }
}

/// For view memory: the pages of `[start, end)`'s blocks written since
/// they were last guarded (all of a block's pages), guarding them again
/// before the caller copies them. `None` if the memory is not a view.
fn guard(start: usize, end: usize) -> Option<Vec<usize>> {
    // A range whose first block the guards hold already (read-only by our
    // hand, or noted absent) is a view: no question to Windows. The
    // question walks the page tables to the end of the pages that share the
    // first one's state, and a guarded view is one long run of read-only
    // pages: 0.6 ms for the title's 174 MB heap, 16 times a frame, and most
    // of the 68 ms a frame of "guards" (run 58).
    // `VICTORY_GUARD_ASK=1` asks every time, as before.
    if !known_view(start / BLOCK) && !is_view(start, end) {
        return None;
    }
    install();
    let mut g = guards();
    let mut written = Vec::new();
    let mut run: Option<usize> = None;
    let (first, last) = (start / BLOCK, end.div_ceil(BLOCK));
    // A frame asks about some 13 GB of view memory, 200,000 blocks, nearly
    // all clean: the clean blocks of the range are counted, not looked up
    // one at a time (the lookups were most of the 60-90 ms a frame of
    // "guards" in run 54, and still 6 ms as an ordered set read off in one
    // pass).
    if g.clean.count(first..last) == last - first {
        // Nothing written, mapped or new since the range was last taken.
        return Some(written);
    }
    let mut uncommitted_until = first;
    let lazy = alias_lazy() && view_guard();
    let mut block = first;
    while block <= last {
        if run.is_none() && block < last {
            // Over the clean blocks ahead in one step (with a run open the
            // next clean block ends it, below).
            block = g.clean.first_out(block, last);
        }
        let mut open = block < last && !g.clean.contains(&block);
        if open && g.absent.contains(&block) {
            // Ordinary commits need no runtime mapping notification. Reuse
            // this asking's query for the following blocks in the same region.
            if block >= uncommitted_until {
                uncommitted_until = uncommitted_end(block);
            }
            open = block >= uncommitted_until;
            if open {
                g.absent.remove(&block);
            }
        }
        if open {
            written.extend(block * BLOCK / PAGE..(block + 1) * BLOCK / PAGE);
            if g.protected.contains(&block) {
                // Written through the runtime, or through another view of
                // its pages ([`alias_lazy`]), and still read-only.
                g.clean.insert(block);
                if lazy {
                    // The view that was written through is open: read-only
                    // again before this block counts as taken, or a later
                    // write through it would not be seen here.
                    guard_views(&mut g, block);
                }
            } else {
                run.get_or_insert(block);
                block += 1;
                continue;
            }
        }
        if let Some(from) = run.take() {
            protect(&mut g, from, block);
        }
        block += 1;
    }
    Some(written)
}

/// Whether `[start, end)` is view memory. The title's views lie in
/// placeholders, mapped and unmapped block by block as it streams, so a
/// range can begin in a block that is not mapped right now: the first
/// pages of the range that are there decide. A range with nothing there
/// counts as a view (its blocks are noted absent, and looked at again when
/// the runtime maps them).
///
/// Looking at the first address only took such a range for "not a view":
/// its copy was marked not watched for good and copied whole at every
/// refresh, around its unmapped pages (run 54: 300 such ranges, 570 MB
/// copied a frame for them, 255 copies a frame reading around holes).
/// `VICTORY_GUARD_HOLES=0` looks at the first address only, as before.
fn is_view(start: usize, end: usize) -> bool {
    use windows_sys::Win32::System::Memory::{
        MEM_COMMIT, MEM_MAPPED, MEMORY_BASIC_INFORMATION, VirtualQuery,
    };
    static HOLES: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    let holes = *HOLES.get_or_init(|| std::env::var_os("VICTORY_GUARD_HOLES").is_none_or(|v| v != "0"));
    let mut at = start;
    loop {
        // SAFETY: plain data filled in by the query.
        let mut info: MEMORY_BASIC_INFORMATION = unsafe { std::mem::zeroed() };
        // SAFETY: a valid out pointer of the right size.
        let n = unsafe { VirtualQuery(at as *const _, &mut info, size_of_val(&info)) };
        if n == 0 {
            return false;
        }
        if info.Type == MEM_MAPPED {
            return true;
        }
        // Committed memory that is no view (the title's heaps, ours), or
        // the answer as it was before.
        if info.State == MEM_COMMIT || !holes {
            return false;
        }
        // A hole (a placeholder, or free): on to what follows it.
        let next = (info.BaseAddress as usize).saturating_add(info.RegionSize);
        if next <= at || next >= end {
            return true;
        }
        at = next;
    }
}

/// Makes blocks `[from, to)` read-only and notes them guarded and clean;
/// block by block if they span views, leaving out any that fail, and
/// noting those not committed (unmapped) absent. The same physical pages
/// at every other view of them are made read-only too: a write through
/// one of those is this memory written, and only a fault can say so.
/// `VICTORY_VIEW_GUARD=0` leaves the other views as they are, as before.
fn protect(g: &mut Guards, from: usize, to: usize) {
    protect_here(g, from, to);
    if !view_guard() {
        return;
    }
    for (base, bytes) in crate::inplace::views_between(from.saturating_mul(BLOCK), to.saturating_mul(BLOCK)) {
        let first = (base / BLOCK).max(from);
        let last = (base.saturating_add(bytes).div_ceil(BLOCK)).min(to);
        for block in first..last {
            guard_views(g, block);
        }
    }
}

/// Makes the other views of `block`'s page read-only, those that are not
/// yet ([`protect_alias`]), and notes all its views guarded together.
fn guard_views(g: &mut Guards, block: usize) {
    let shown = crate::inplace::pages_of(block * BLOCK);
    // One view (nothing else to guard), or the page the title shows
    // wherever it has nothing (thousands of views): each view of that one
    // is guarded by itself.
    if shown.len() < 2 || shown.len() > MANY_VIEWS {
        return;
    }
    #[cfg(feature = "diagnostics")]
    ALIASES[0].fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    for alias in shown {
        let alias = alias / BLOCK;
        g.aliased.insert(alias);
        if alias != block {
            protect_alias(g, alias);
        }
    }
}

/// Whether a write through one view of a guarded page leaves the page's
/// other views read-only (`VICTORY_ALIAS_LAZY=1`; off by default).
///
/// The views of a guarded page are guarded together, and a write through
/// one of them opened them all: a change of protection for each view, and
/// another for each when the page was next taken. In the world that is
/// about 1,600 views opened a frame for writes through another view, and
/// as many made read-only again (the memory line's "views opened by a
/// write through another"); each is a system call, and under Wine the
/// kernel then flushes the page tables of every processor that runs a
/// thread of the process.
///
/// Only the view that is written through has to be open. With the switch
/// the page's other views stay read-only and are noted not clean, which is
/// what their copies of title memory go by: the next check at such a view
/// reports the block written and notes it clean, as for a block written
/// through the runtime. Before that it makes the page's open views
/// read-only again ([`guard_views`]), so that the next write through any
/// of them faults and is noted at every view, as it is without the switch.
fn alias_lazy() -> bool {
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *ON.get_or_init(|| std::env::var_os("VICTORY_ALIAS_LAZY").is_some_and(|v| v == "1"))
}

/// Views of one page past which its views are not guarded together.
pub(crate) const MANY_VIEWS: usize = 64;

/// Whether all the views of a guarded page are guarded together
/// (`VICTORY_VIEW_GUARD`).
fn view_guard() -> bool {
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *ON.get_or_init(|| std::env::var_os("VICTORY_VIEW_GUARD").is_none_or(|v| v != "0"))
}

/// Diagnostics: blocks guarded together with their other views, blocks
/// opened because another view of theirs was written, and blocks opened
/// because a view of theirs was mapped; since the start.
#[cfg(feature = "diagnostics")]
pub(crate) static ALIASES: [std::sync::atomic::AtomicU64; 3] = [const { std::sync::atomic::AtomicU64::new(0) }; 3];

/// Makes `block` read-only: another view of pages a copy has just taken
/// through its own view, so that a write through this one faults too. It is
/// not noted clean. The copies of title memory at this view have not taken
/// the pages: noted clean, the block would not be reported written at their
/// next check and they would keep the bytes from before the write (`guard`
/// reports a block that is read-only and not clean as written, then notes it
/// clean). A block that is clean stays so: had the pages been written since
/// its copies took them, `open` would have opened it, or noted it not clean
/// ([`alias_lazy`]).
fn protect_alias(g: &mut Guards, block: usize) {
    use windows_sys::Win32::System::Memory::{PAGE_READONLY, VirtualProtect};
    if g.protected.contains(&block) {
        return;
    }
    let mut old = 0;
    // SAFETY: title view memory; only its protection changes.
    if unsafe { VirtualProtect((block * BLOCK) as *const _, BLOCK, PAGE_READONLY, &mut old) } != 0 {
        g.protected.insert(block);
    }
}

/// [`protect`] for one range, without the other views of its pages.
fn protect_here(g: &mut Guards, from: usize, to: usize) {
    use windows_sys::Win32::System::Memory::{PAGE_READONLY, VirtualProtect};
    let set = |from: usize, to: usize| {
        let mut old = 0;
        // SAFETY: title view memory; only its protection changes.
        unsafe {
            VirtualProtect(
                (from * BLOCK) as *const _,
                (to - from) * BLOCK,
                PAGE_READONLY,
                &mut old,
            ) != 0
        }
    };
    let note = |g: &mut Guards, from: usize, to: usize| {
        g.protected.extend(from..to);
        g.clean.extend(from..to);
    };
    if set(from, to) {
        note(g, from, to);
        return;
    }
    for block in from..to {
        if set(block, block + 1) {
            note(g, block, block + 1);
        } else if block < uncommitted_end(block) {
            g.absent.insert(block);
        }
    }
}

/// The end (exclusive) of the whole uncommitted blocks starting at `block`.
fn uncommitted_end(block: usize) -> usize {
    use windows_sys::Win32::System::Memory::{
        MEM_FREE, MEM_RESERVE, MEMORY_BASIC_INFORMATION, VirtualQuery,
    };
    // SAFETY: plain data filled in by the query.
    let mut info: MEMORY_BASIC_INFORMATION = unsafe { std::mem::zeroed() };
    // SAFETY: a valid out pointer of the right size.
    let n = unsafe { VirtualQuery((block * BLOCK) as *const _, &mut info, size_of_val(&info)) };
    if n != 0 && matches!(info.State, MEM_RESERVE | MEM_FREE) {
        (info.BaseAddress as usize).saturating_add(info.RegionSize) / BLOCK
    } else {
        block
    }
}

/// Gives write access back to the guarded blocks of `[start, end)` and
/// notes them written; true if any was guarded. The same physical pages at
/// every other view of them are opened too, or with [`alias_lazy`] noted
/// not clean: the write that faulted (or is ours,
/// `crate::host::copy_mapped`) goes through one view, and every guard over
/// the pages must copy them again.
fn open(g: &mut Guards, start: usize, end: usize) -> bool {
    let any = open_here(g, start, end);
    if start >= end || g.aliased.is_empty() {
        return any;
    }
    let lazy = alias_lazy();
    let aliased = g.aliased.within(start / BLOCK..end.div_ceil(BLOCK));
    for block in aliased {
        g.aliased.remove(&block);
        for alias in crate::inplace::pages_of(block * BLOCK) {
            let other = alias / BLOCK;
            // The other view takes the page again at its next check: it
            // stays read-only for that with [`alias_lazy`], else it is
            // opened like the written one.
            let noted = other != block
                && if lazy {
                    g.clean.remove(&other)
                } else {
                    open_here(g, alias, alias.saturating_add(BLOCK))
                };
            if noted {
                #[cfg(feature = "diagnostics")]
                ALIASES[1].fetch_add(1, std::sync::atomic::Ordering::Relaxed);
            }
            g.aliased.remove(&other);
        }
    }
    any
}

/// [`open`] for one range, without the other views of its pages.
fn open_here(g: &mut Guards, start: usize, end: usize) -> bool {
    use windows_sys::Win32::System::Memory::{PAGE_READWRITE, VirtualProtect};
    let blocks = g.protected.within(start / BLOCK..end.div_ceil(BLOCK));
    for &block in &blocks {
        g.protected.remove(&block);
        g.clean.remove(&block);
        let mut old = 0;
        // SAFETY: a block we made read-only.
        unsafe { VirtualProtect((block * BLOCK) as *const _, BLOCK, PAGE_READWRITE, &mut old) };
    }
    !blocks.is_empty()
}

/// Before our own write into title memory `[at, at + len)` through the
/// kernel (which does not fault into our handler): opens its guarded blocks.
/// The runtime calls it (as `kernel_will_write`) before the title's kernel
/// reads into its own memory.
pub fn writing(at: usize, len: usize) {
    // The length is the title's (`fread`'s size times count, saturated).
    open(&mut guards(), at, at.saturating_add(len));
    // A placed texture there changes with no descriptor written.
    crate::descriptor::host::remapped(at, len);
}

/// How many times [`kernel_write`] makes a system call that is refused.
const KERNEL_WRITE_TRIES: u32 = 8;

/// Runs `write`, a system call that writes title memory `[at, at + len)`,
/// with the range's guarded blocks open ([`writing`]); `refused` says of
/// its result whether the kernel could not write there (`ERROR_NOACCESS`).
///
/// The kernel does not fault into our handler, and nothing holds the blocks
/// open between the opening and the call: a copy on another thread can take
/// one meanwhile and leave it read-only again, at its own view or at
/// another view of the same pages. The call is then refused. It is made
/// again after another opening, [`KERNEL_WRITE_TRIES`] times at most; what
/// is still refused then is not ours to open, and that result is returned.
pub fn kernel_write<T>(at: usize, len: usize, mut write: impl FnMut() -> T, refused: impl Fn(&T) -> bool) -> T {
    static AGAIN: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    writing(at, len);
    let mut result = write();
    let mut tries = 1;
    while refused(&result) && tries < KERNEL_WRITE_TRIES {
        // The guards alone: `writing` has told the descriptors already.
        open(&mut guards(), at, at.saturating_add(len));
        result = write();
        tries += 1;
    }
    if tries > 1 {
        let calls = AGAIN.fetch_add(1, std::sync::atomic::Ordering::Relaxed) + 1;
        if calls <= 8 || calls.is_power_of_two() {
            tracing::warn!(
                at = format_args!("{at:#x}"),
                len,
                tries,
                landed = !refused(&result),
                calls,
                "a system call's write into title memory was refused (a block guarded again meanwhile); made again"
            );
        }
    }
    result
}

/// The runtime mapped a view of the physical bytes `[offset, offset + len)`
/// of `section` (`crate::inplace::title_memory_view`): the view is
/// writable, so the same bytes guarded at another view must be checked
/// again — and are, the pages noted written, which also has the next check
/// guard the new view (`protect`).
pub(crate) fn views_mapped(section: usize, offset: u64, len: usize) {
    if !view_guard() {
        return;
    }
    let ranges = crate::inplace::views_of_section(section, offset, len);
    if ranges.is_empty() {
        return;
    }
    let mut g = guards();
    for &(at, n) in &ranges {
        if open_here(&mut g, at, at.saturating_add(n)) {
            #[cfg(feature = "diagnostics")]
            ALIASES[2].fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        }
    }
}

/// Held shared by a read of title memory in place, and alone by the runtime
/// while it changes what title memory shows.
///
/// The runtime does not change a mapping in one step. To unmap one page of
/// a view it unmaps the whole view and maps what stays again
/// (`xmem.rs` `unmap`), and a view it maps is a reservation until the next
/// call commits it (`map`, then `commit`). For that moment pages the title
/// never gave up are "reserved, never committed", and a thread reading
/// them in place takes an access violation: run 71 in `Layout::detile`,
/// run 74 in the hash before it, both under `Staging::refresh_now`, which
/// had asked whether the texture was all mapped and been told yes. Asking
/// cannot help; not changing the mapping while such a read is under way
/// does.
static MAPPING: std::sync::RwLock<()> = std::sync::RwLock::new(());

/// What the runtime holds while it changes what title memory shows
/// ([`title_memory_remapping`]).
pub struct Remapping(#[allow(dead_code)] std::sync::RwLockWriteGuard<'static, ()>);

/// The runtime is about to map, unmap or move physical pages of title
/// memory: until what it returns is dropped, no read of title memory in
/// place is under way and none begins ([`title_memory_reading`]). Taken
/// around the whole change, the unmapping and the mapping again.
pub fn title_memory_remapping() -> Remapping {
    Remapping(MAPPING.write().unwrap_or_else(|e| e.into_inner()))
}

/// What a read of title memory in place holds ([`title_memory_reading`]).
pub struct Reading(#[allow(dead_code)] std::sync::RwLockReadGuard<'static, ()>);

/// For reading title memory in place: until what it returns is dropped,
/// the runtime changes no mapping, so memory found mapped stays mapped.
/// Not to be taken twice by one thread, nor held across anything that
/// maps title memory.
pub fn title_memory_reading() -> Reading {
    Reading(MAPPING.read().unwrap_or_else(|e| e.into_inner()))
}

/// [`title_memory_reading`] if it can be had at once: `None` while the
/// runtime changes a mapping (or waits to), for a caller that has another
/// way to read and would rather not wait.
pub fn title_memory_reading_now() -> Option<Reading> {
    match MAPPING.try_read() {
        Ok(guard) => Some(Reading(guard)),
        Err(std::sync::TryLockError::Poisoned(e)) => Some(Reading(e.into_inner())),
        Err(std::sync::TryLockError::WouldBlock) => None,
    }
}

/// The runtime mapped or unmapped title memory `[at, at + len)`: what it
/// shows is new and read-write, so it is no longer guarded (nor known
/// unmapped).
pub fn title_memory_remapped(at: usize, len: usize) {
    // A placed texture there arrives, goes or changes with no descriptor
    // written.
    crate::descriptor::host::remapped(at, len);
    // The views the runtime told us of there are no longer what it shows.
    crate::inplace::views_gone(at, len);
    // And nothing stays in place over it.
    crate::inplace::title_memory_freeing(at, len);
    let mut g = guards();
    let range = at / BLOCK..at.saturating_add(len).div_ceil(BLOCK);
    let absent = g.absent.within(range.clone());
    for block in absent {
        g.absent.remove(&block);
    }
    let blocks = g.protected.within(range);
    for block in blocks {
        g.protected.remove(&block);
        g.clean.remove(&block);
    }
    let aliased = g
        .aliased
        .within(at / BLOCK..at.saturating_add(len).div_ceil(BLOCK));
    for block in aliased {
        g.aliased.remove(&block);
    }
}

/// Handles a write access violation at `at` if the block belongs to our guards
/// or became writable concurrently.
pub(crate) fn handle_write_fault(at: usize) -> bool {
    let mut g = guards();
    if open(&mut g, at, at + 1) {
        #[cfg(feature = "diagnostics")]
        crate::copystat::add(crate::copystat::C::GuardFaults, 1);
        return true;
    }
    writable(at)
}

/// Registers the handler that takes writes to guarded blocks, once, ahead
/// of the crash reporter's.
fn install() {
    use windows_sys::Win32::Foundation::{EXCEPTION_ACCESS_VIOLATION, NTSTATUS};
    use windows_sys::Win32::System::Diagnostics::Debug::{
        AddVectoredExceptionHandler, EXCEPTION_CONTINUE_EXECUTION, EXCEPTION_CONTINUE_SEARCH,
        EXCEPTION_POINTERS,
    };
    unsafe extern "system" fn on_write(info: *mut EXCEPTION_POINTERS) -> i32 {
        // SAFETY: the system passes the exception being dispatched.
        let r = unsafe { &*(*info).ExceptionRecord };
        const WRITE: usize = 1;
        if r.ExceptionCode != EXCEPTION_ACCESS_VIOLATION as NTSTATUS
            || r.NumberParameters < 2
            || r.ExceptionInformation[0] != WRITE
        {
            return EXCEPTION_CONTINUE_SEARCH;
        }
        let at = r.ExceptionInformation[1];
        // Held across both checks: another thread may have opened the block
        // since this one faulted, and a copy may have guarded it again since
        // (then it is ours again, not read-only for some other reason).
        if handle_write_fault(at) {
            EXCEPTION_CONTINUE_EXECUTION
        } else {
            EXCEPTION_CONTINUE_SEARCH
        }
    }
    static ONCE: std::sync::Once = std::sync::Once::new();
    // SAFETY: the handler only touches our guard state and protections.
    ONCE.call_once(|| unsafe {
        AddVectoredExceptionHandler(1, Some(on_write));
    });
}

/// Whether `at` is committed read-write memory now.
fn writable(at: usize) -> bool {
    use windows_sys::Win32::System::Memory::{
        MEM_COMMIT, MEMORY_BASIC_INFORMATION, PAGE_READWRITE, VirtualQuery,
    };
    // SAFETY: plain data filled in by the query.
    let mut info: MEMORY_BASIC_INFORMATION = unsafe { std::mem::zeroed() };
    // SAFETY: a valid out pointer of the right size.
    let n = unsafe { VirtualQuery(at as *const _, &mut info, size_of_val(&info)) };
    n != 0 && info.State == MEM_COMMIT && info.Protect == PAGE_READWRITE
}

